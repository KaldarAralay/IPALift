#!/usr/bin/env python3
"""Verify IPALift release artifacts from isolated environments.

The default mode checks archive contents, installs the wheel and source
distribution into separate temporary virtual environments, and exercises the
installed command line. Supplying --ghidra-home additionally runs the complete
pipeline twice from each artifact, validates every JSON artifact, and compares
all generated bytes for determinism.
"""

